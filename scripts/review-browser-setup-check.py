import asyncio, json
from playwright.async_api import async_playwright, expect
async def main():
 async with async_playwright() as p:
  b=await p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
  page=await b.new_page(viewport={'width':1440,'height':1000})
  await page.goto('http://localhost:5173/teams?persona=coordinator')
  await page.get_by_role('button',name='New team',exact=True).click()
  await page.get_by_label('Team name').fill('Browser Example Club')
  await page.get_by_label('Default tickets / game').fill('4')
  await page.get_by_role('button',name='Add team',exact=True).click()
  outer=page.get_by_role('dialog',name='Browser Example Club',exact=True)
  await expect(outer).to_be_visible()
  await outer.get_by_role('button',name='Import (paste)',exact=True).click()
  inner=page.get_by_role('dialog',name='Import schedule',exact=True)
  await expect(inner).to_be_visible()
  await inner.get_by_label('Paste synthetic CSV schedule').fill('date,time,opponent,promotions,tickets\n2026-11-27,19:00,Synthetic CSV Opponent,,4')
  await inner.get_by_role('button',name='Parse schedule',exact=True).click()
  await expect(inner.get_by_text('Synthetic CSV Opponent',exact=False)).to_be_visible()
  await inner.get_by_role('button',name='Import 1 games',exact=True).click()
  await expect(inner.get_by_text('Imported 1 games',exact=False)).to_be_visible()
  await page.keyboard.press('Escape')
  await expect(inner).not_to_be_visible()
  await expect(outer).to_be_visible()
  await outer.get_by_role('button',name='Import CSV',exact=True).click()
  csv=page.get_by_role('dialog',name='Import schedule from CSV',exact=True)
  await csv.get_by_label('Synthetic schedule CSV file').set_input_files({'name':'synthetic.csv','mimeType':'text/csv','buffer':b'date,time,opponent,promotions,tickets\n2026-12-01,19:30,Another Synthetic Opponent,,4'})
  await expect(csv.get_by_role('button',name='Import CSV privately',exact=True)).to_be_disabled()
  await csv.get_by_role('button',name='Preview CSV',exact=True).click()
  await expect(csv.get_by_text('Private import preview',exact=False)).to_be_visible()
  await csv.get_by_role('button',name='Import CSV privately',exact=True).click()
  await expect(csv.get_by_text('Imported 1 games',exact=False)).to_be_visible()
  await page.keyboard.press('Escape'); await page.keyboard.press('Escape')
  await page.get_by_role('link',name='Coordinator workspace',exact=True).click()
  await expect(page.locator('article').filter(has_text='Another Synthetic Opponent')).to_contain_text('Private')
  await page.get_by_role('link',name='Contacts & history',exact=True).click()
  await page.get_by_label('Search contacts').fill('employee@example.invalid')
  await page.get_by_role('button',name='Edit',exact=True).click()
  d=page.get_by_role('dialog',name='Edit contact',exact=True)
  await d.get_by_label('Active in this app',exact=False).uncheck()
  await d.get_by_role('button',name='Save',exact=True).click()
  await expect(d).not_to_be_visible()
  await page.get_by_role('button',name='Sync synthetic directory',exact=True).click()
  await expect(page.get_by_role('cell',name='Inactive in app',exact=False)).to_be_visible()
  await page.get_by_role('button',name='Edit',exact=True).click()
  d=page.get_by_role('dialog',name='Edit contact',exact=True)
  await d.get_by_label('Active in this app',exact=False).check()
  await d.get_by_role('button',name='Save',exact=True).click()
  await expect(d).not_to_be_visible()
  await page.get_by_role('link',name='Advisory settings',exact=True).click()
  await expect(page.get_by_role('heading',name='Advisory allocation settings',exact=True)).to_be_visible()
  await expect(page.get_by_label('Employee',exact=True)).to_have_value('0.2')
  await expect(page.get_by_role('slider')).to_have_count(4)
  print(json.dumps({'status':'PASS','checks':['new team','local pasted CSV preview/import','uploaded CSV preview/private import','nested dialog Escape','app employee override survives mock sync','configurable advisory category values']}))
  await b.close()
asyncio.run(main())
