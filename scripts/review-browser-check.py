import asyncio, json
from pathlib import Path

# Optional local QA using existing Python Playwright + Chromium. Start a fresh review fixture first.
Path('/tmp/ticket-manager-review-browser').mkdir(parents=True, exist_ok=True)
from playwright.async_api import async_playwright, expect

async def main():
  async with async_playwright() as p:
    browser = await p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    page = await browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    await page.goto('http://localhost:5173/')
    await expect(page.get_by_role('heading',name='Make every ticket count')).to_be_visible()
    await page.screenshot(path='/tmp/ticket-manager-review-browser/coordinator.png',full_page=True)
    await page.get_by_role('button',name='Add dated event',exact=True).click()
    dialog=page.get_by_role('dialog')
    await expect(dialog).to_be_visible()
    await page.get_by_label('Event title').fill('Browser Synthetic Gathering')
    await page.get_by_label('Date & time (UTC)').fill('2026-12-20T19:00')
    await page.get_by_label('Ticket inventory').fill('4')
    await page.get_by_role('button',name='Create private event').click()
    await expect(dialog).not_to_be_visible()
    card=page.locator('article').filter(has=page.get_by_role('heading',name='Browser Synthetic Gathering',exact=True))
    await expect(card).to_contain_text('Private')
    await card.get_by_role('checkbox').check()
    await page.get_by_role('button',name='Save release settings').click()
    await expect(card).to_contain_text('Released to requesters')
    await page.get_by_label('Synthetic persona').select_option('employee')
    await expect(page.get_by_role('heading',name='Find your next event')).to_be_visible()
    await expect(page.get_by_role('button',name='Save release settings')).to_have_count(0)
    await expect(page.get_by_role('link',name='Advisory settings')).to_have_count(0)
    await expect(page.get_by_text('Example Rivals',exact=False)).to_have_count(0)
    card=page.locator('article').filter(has=page.get_by_role('heading',name='Synthetic Comets · Sample Visitors',exact=True))
    await card.get_by_role('button',name='Express interest',exact=True).click()
    dialog=page.get_by_role('dialog')
    await dialog.get_by_label('Tickets requested').fill('1')
    await dialog.get_by_role('checkbox').check()
    await dialog.get_by_label('Concise business justification').fill('Synthetic employee interest for browser QA.')
    await dialog.get_by_role('button',name='Record interest',exact=True).click()
    await expect(dialog).not_to_be_visible()
    await expect(page.get_by_role('status')).to_contain_text('No tickets were allocated')
    await page.get_by_label('Synthetic persona').select_option('rep')
    await expect(page.get_by_role('heading',name='Find your next event')).to_be_visible()
    card=page.locator('article').filter(has=page.get_by_role('heading',name='Synthetic Comets · Sample Visitors',exact=True))
    await card.get_by_role('button',name='Express interest',exact=True).click()
    dialog=page.get_by_role('dialog')
    await dialog.get_by_label('Customer / business').select_option('Juniper Example Labs')
    for item in await dialog.get_by_role('checkbox').all(): await item.check()
    await dialog.get_by_label('Related opportunity (optional)').fill('Browser renewal QA')
    await dialog.get_by_label('Concise business justification').fill('Browser QA customer relationship discussion.')
    await dialog.get_by_role('button',name='Record interest',exact=True).click()
    await expect(dialog).not_to_be_visible()
    await page.get_by_label('Synthetic persona').select_option('coordinator')
    await expect(page.get_by_role('heading',name='Make every ticket count')).to_be_visible()
    await page.get_by_role('button',name='2 · Review interest').click()
    card=page.locator('article').filter(has_text='Browser QA customer relationship discussion.')
    await card.get_by_role('button',name='Assign tickets',exact=True).click()
    dialog=page.get_by_role('dialog')
    await dialog.get_by_label('Decision / override reason').fill('Coordinator chooses this synthetic customer discussion.')
    await dialog.get_by_role('button',name='Record allocation',exact=True).click()
    await expect(dialog).not_to_be_visible()
    await expect(card).to_contain_text('2 allocated')
    await page.get_by_role('button',name='3 · Transfers & attendance').click()
    card=page.locator('article').filter(has_text='Alex Sample').filter(has_text='Sample Visitors').first
    await card.get_by_role('button',name='Record manual transfer',exact=True).click()
    dialog=page.get_by_role('dialog')
    await dialog.get_by_label('Manual reference / note').fill('Synthetic provider-app step completed')
    await dialog.get_by_role('checkbox').check()
    await dialog.get_by_role('button',name='Save local record',exact=True).click()
    await expect(dialog).not_to_be_visible()
    await expect(card).to_contain_text('Recorded locally')
    past=page.locator('article').filter(has_text='Past Demo Night').first
    await past.get_by_role('button',name='Update attendance',exact=True).click()
    dialog=page.get_by_role('dialog')
    await expect(dialog.get_by_label('Attendance outcome')).to_have_value('unknown')
    await dialog.get_by_label('Attendance outcome').select_option('no_show')
    await dialog.get_by_label('Evidence / coordinator note').fill('Synthetic confirmation for browser test.')
    await dialog.get_by_role('button',name='Save local record',exact=True).click()
    await expect(dialog).not_to_be_visible()
    await expect(past).to_contain_text('Confirmed no-show')
    await page.get_by_role('button',name='Mock messages',exact=True).click()
    await page.get_by_role('button',name='Add availability preview to mock outbox',exact=True).click()
    await expect(page.get_by_text('Tickets available — express interest',exact=True)).to_be_visible()
    await page.get_by_role('checkbox',name='Enable local follow-up mock flow').check()
    await page.get_by_role('button',name='Save local template',exact=True).click()
    await expect(page.get_by_role('button',name='Add saved follow-up to mock outbox')).to_be_enabled()
    await page.get_by_role('button',name='Add saved follow-up to mock outbox').click()
    await expect(page.get_by_role('heading',name='How was the event?',exact=True)).to_be_visible()
    await page.get_by_role('link',name='Contacts & history').click()
    await page.get_by_label('Search contacts').fill('Juniper')
    await expect(page.get_by_role('cell',name='Alex Sample',exact=False)).to_be_visible()
    await page.get_by_role('button',name='History',exact=True).first.click()
    await expect(page.get_by_role('dialog')).to_contain_text('Ticket allocations across seasons')
    await page.keyboard.press('Escape')
    await expect(page.get_by_role('dialog')).not_to_be_visible()
    await page.goto('http://localhost:5173/')
    await expect(page.get_by_role('heading',name='Make every ticket count')).to_be_visible()
    await page.set_viewport_size({'width':390,'height':844})
    await page.screenshot(path='/tmp/ticket-manager-review-browser/mobile.png',full_page=True)
    assert await page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'mobile horizontal overflow'
    await page.get_by_role('button',name='Add dated event',exact=True).click()
    await expect(page.get_by_role('dialog')).to_be_visible()
    for _ in range(15): await page.keyboard.press('Tab')
    assert await page.evaluate('!!document.activeElement.closest("[role=dialog]")'), 'dialog focus escaped'
    await page.keyboard.press('Escape')
    await expect(page.get_by_role('dialog')).not_to_be_visible()
    assert not errors, errors
    print(json.dumps({'status':'PASS','checks':['create private event','release selected inventory','requester role privacy','employee self interest','customer multi-contact interest','coordinator assignment','manual transfer record','confirmed attendance evidence','mock announcements','optional mock follow-up','cross-season history','mobile overflow','dialog focus trap and Escape'], 'pageErrors':errors}))
    await browser.close()

asyncio.run(main())
